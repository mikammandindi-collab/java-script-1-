let firstName = "Mika" // This is a comment explaining that the firstName variable is constant and cannot be reassigned.
let lastName = "Mandindi" // This is a comment explaining that the lastName variable is constant and cannot be reassigned.

let age = 21 // This variable holds the age of the person.
let fullName = firstName + " " + lastName // This variable concatenates the firstName and lastName variables to create a full name.
let greeting = "Hello, my name is " + fullName + " and I am " + age + " years old." // This variable creates a greeting message using the fullName and age variables.

console.log(greeting) // This line logs the greeting message to the console.

age = 22 // This line reassigns the age variable to a new value of 22.
console.log("I am now " + age + " years old.") // This line logs the updated age to the console.

